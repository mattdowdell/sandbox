#! /usr/bin/env bash

set -eu -o pipefail

tools=`bingo list | tail -n+3 | awk '{print $1}'`

echo "# Generated by ./tools/bingo-justfile.sh. DO NOT EDIT."
echo
echo 'gopath := shell("go env GOPATH")'
echo

for tool in $tools
do
	filename=`bingo list | grep "\b$tool\b" | awk '{print $2}'`

	echo "${tool} := join(gopath, \"bin\", \"$filename\")"
	echo
	echo "[private]"
	echo "install-${tool}:"
	if [[ "$tool" == protoc-gen-* ]]
	then
		# use symlink for protoc plugins
		# avoids needing to maintain versions in buf.gen.yaml
		echo "    bingo get -l ${tool}"
	else
		echo "    bingo get ${tool}"
	fi
	echo
done
